class PolicyError(Exception):
    """业务规则冲突，附带触发的规则编号与可读原因。"""

    def __init__(self, rule: str, reason: str):
        self.rule = rule
        self.reason = reason
        super().__init__(f"[{rule}] {reason} —— {RULES[rule]}")


class DomainError(Exception):
    """数据/状态类错误（不存在、状态非法等），非规则冲突。"""
